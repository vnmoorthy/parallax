"""Dataset registry: bundled CSVs from <repo>/datasets/registry.json + user uploads (docs/SPEC.md §4, §8).

The bundled CSVs are generated by another process; if the registry or any file is missing we expose a small
built-in dataset generated in memory so the API always has something to run on.
"""
