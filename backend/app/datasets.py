log = logging.getLogger("parallax.datasets")

MAX_UPLOAD_BYTES = 25 * 1024 * 1024
TEXT_MEAN_LENGTH = 25
DEFAULT_QUESTIONS = [
    "What are the strongest patterns in this dataset and what explains them?",
    "Which segments stand out as unusual, and why?",
    "What should we investigate next based on the outliers?",
]
FALLBACK_ID = "demo_support_tickets"


class DatasetError(Exception):
    def __init__(self, code: str, message: str, status: int = 400) -> None:
        super().__init__(message)
        self.code = code
        self.status = status


# ── column typing / profiling (pandas) ───────────────────────────────────
def column_type(series: pd.Series) -> str:
    dt = series.dtype
    if pd.api.types.is_bool_dtype(dt):
        return "boolean"
    if pd.api.types.is_integer_dtype(dt):
        return "integer"
    if pd.api.types.is_float_dtype(dt):
        return "number"
    if pd.api.types.is_datetime64_any_dtype(dt):
        return "datetime"
    return "string"


def _scalar(v: Any) -> Any:
    v = jsonable(v)
    if isinstance(v, float) and not math.isfinite(v):
        return None
    return v


def profile_frame(df: pd.DataFrame, top_n: int = 5) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for col in df.columns:
        s = df[col]
        typ = column_type(s)
        entry: dict[str, Any] = {
            "type": typ,
            "nulls": int(s.isna().sum()),
            "distinct": int(s.nunique(dropna=True)),
            "min": None,
            "max": None,
            "top": [],
        }
        non_null = s.dropna()
        if len(non_null):
            if typ in ("integer", "number", "datetime"):
                try:
                    entry["min"] = _scalar(non_null.min())
                    entry["max"] = _scalar(non_null.max())
                except Exception:
                    pass
            elif typ == "string":
                try:
                    lengths = non_null.astype(str).str.len()
                    entry["min"] = int(lengths.min())
                    entry["max"] = int(lengths.max())
                except Exception:
                    pass
            try:
                vc = non_null.astype(str).value_counts().head(top_n)
                entry["top"] = [{"value": str(k)[:80], "count": int(v)} for k, v in vc.items()]
            except Exception:
                entry["top"] = []
        out[str(col)] = entry
    return out


def infer_text_columns(df: pd.DataFrame, mean_len: float = TEXT_MEAN_LENGTH) -> list[str]:
    cols: list[str] = []
    for col in df.columns:
        s = df[col]
        if not (pd.api.types.is_object_dtype(s.dtype) or pd.api.types.is_string_dtype(s.dtype)):
            continue
        non_null = s.dropna().astype(str)
        if non_null.empty:
            continue
        if float(non_null.str.len().mean()) > mean_len:
            cols.append(str(col))
    return cols


def frame_rows(df: pd.DataFrame, limit: int) -> list[list[Any]]:
    head = df.head(limit)
    return [[_scalar(v) for v in row] for row in head.itertuples(index=False, name=None)]


def read_csv_bytes(data: bytes) -> pd.DataFrame:
    try:
        return pd.read_csv(io.BytesIO(data), low_memory=False)
    except UnicodeDecodeError:
        return pd.read_csv(io.BytesIO(data), low_memory=False, encoding="latin-1")


# ── dataset object ───────────────────────────────────────────────────────
@dataclass
class Dataset:
    id: str
    name: str
    description: str
    source: str  # "bundled" | "upload"
    text_columns: list[str] = field(default_factory=list)
    suggested_questions: list[str] = field(default_factory=list)
    path: Path | None = None
    _csv: str | None = field(default=None, repr=False)
    _frame: pd.DataFrame | None = field(default=None, repr=False)
    _mtime: float | None = field(default=None, repr=False)
    _lock: threading.Lock = field(default_factory=threading.Lock, repr=False)

    # ── data access ──────────────────────────────────────────────────────
    def frame(self) -> pd.DataFrame:
        with self._lock:
            if self.path is not None:
                mtime = self.path.stat().st_mtime
                if self._frame is None or self._mtime != mtime:
                    self._frame = pd.read_csv(self.path, low_memory=False)
                    self._mtime = mtime
            elif self._frame is None:
                if self._csv is None:
                    raise DatasetError("dataset_unavailable", f"dataset {self.id} has no data", 404)
                self._frame = pd.read_csv(io.StringIO(self._csv))
            assert self._frame is not None
            return self._frame

    def csv_text(self) -> str:
        if self.path is not None:
            return self.path.read_text(encoding="utf-8", errors="replace")
        if self._csv is None:
            raise DatasetError("dataset_unavailable", f"dataset {self.id} has no data", 404)
        return self._csv

    def profile(self) -> dict[str, dict[str, Any]]:
        return profile_frame(self.frame())

    @property
    def rows(self) -> int:
        return len(self.frame())

    @property
    def columns(self) -> list[dict[str, str]]:
        df = self.frame()
        return [{"name": str(c), "type": column_type(df[c])} for c in df.columns]

    def column_names(self) -> list[str]:
        return [str(c) for c in self.frame().columns]

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "rows": self.rows,
            "columns": self.columns,
            "source": self.source,
            "text_columns": list(self.text_columns),
            "suggested_questions": list(self.suggested_questions),
        }

    def preview(self, limit: int = 20) -> dict[str, Any]:
        df = self.frame()
        limit = max(1, min(int(limit), 200))
        return {"columns": [str(c) for c in df.columns], "rows": frame_rows(df, limit), "profile": profile_frame(df)}


# ── built-in fallback dataset ────────────────────────────────────────────
def build_fallback_csv(rows: int = 300, seed: int = 7) -> str:
    rng = random.Random(seed)
    regions = ["North America", "Europe", "APAC", "LATAM"]
    products = ["Analytics", "Billing", "Mobile App", "API", "Dashboard"]
    priorities = ["low", "medium", "high", "urgent"]
    channels = ["email", "chat", "phone", "web form"]
    openers = ["Customer reports that", "User is frustrated because", "Account admin asks why",
               "New signup mentions that", "Enterprise client escalated:"]
    issues = {
        "Analytics": ["the funnel report shows different totals than the dashboard",
                      "scheduled exports arrive hours late", "custom metrics disappear after saving"],
        "Billing": ["the invoice double charged the annual plan", "the proration on seat changes looks wrong",
                    "the receipt PDF is missing the VAT number"],
        "Mobile App": ["push notifications stopped arriving on Android", "the app crashes when opening a saved view",
                       "offline mode loses edits after sync"],
        "API": ["rate limits are hit far below the documented quota", "webhooks retry forever on a 410 response",
                "pagination cursors expire too quickly"],
        "Dashboard": ["the shared dashboard link asks external viewers to log in", "filters reset on every refresh",
                      "the dark theme makes chart labels unreadable"],
    }
    closers = ["and wants a fix before the quarterly review.", "which blocks their onboarding.",
               "and is considering downgrading.", "but is otherwise happy with support.", "and asked for a credit."]
    start = date(2026, 1, 1)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["ticket_id", "created_at", "region", "product", "priority", "channel", "resolution_hours", "csat",
                "escalated", "subject"])
    for i in range(1, rows + 1):
        product = rng.choice(products)
        priority = rng.choices(priorities, weights=[4, 5, 3, 1])[0]
        base_hours = {"low": 40, "medium": 24, "high": 10, "urgent": 4}[priority]
        hours = round(max(0.5, rng.gauss(base_hours, base_hours / 3)), 1)
        csat = max(1, min(5, round(rng.gauss(4.2 - (hours / 30), 0.8))))
        escalated = 1 if (priority in ("high", "urgent") and rng.random() < 0.35) else (1 if rng.random() < 0.05 else 0)
        subject = f"{rng.choice(openers)} {rng.choice(issues[product])} {rng.choice(closers)}"
        w.writerow([f"T-{i:05d}", (start + timedelta(days=rng.randint(0, 240))).isoformat(), rng.choice(regions),
                    product, priority, rng.choice(channels), hours, csat, escalated, subject])
    return buf.getvalue()


def fallback_dataset() -> Dataset:
    return Dataset(
        id=FALLBACK_ID, name="Demo: support tickets (built-in)",
        description="300 synthetic support tickets generated in memory — available even before the bundled "
                    "datasets are generated.",
        source="bundled", text_columns=["subject"],
        suggested_questions=["Which products and regions drive long resolution times and low CSAT?",
                             "What themes show up in escalated tickets?"],
        _csv=build_fallback_csv(),
    )


# ── registry ─────────────────────────────────────────────────────────────
class DatasetRegistry:
    """Bundled datasets (re-read from registry.json when it changes) + uploads (own registry.json)."""

    def __init__(self, datasets_dir: Path | str | None = None, uploads_dir: Path | str | None = None, *,
                 include_fallback: bool = True) -> None:
        if datasets_dir is None or uploads_dir is None:
            from app.config import settings

            datasets_dir = datasets_dir or settings.datasets_dir
            uploads_dir = uploads_dir or settings.uploads_dir
        self.datasets_dir = Path(datasets_dir)
        self.uploads_dir = Path(uploads_dir)
        self.uploads_dir.mkdir(parents=True, exist_ok=True)
        self.include_fallback = include_fallback
        self._bundled: dict[str, Dataset] = {}
        self._bundled_sig: tuple[Any, ...] | None = None
        self._uploads: dict[str, Dataset] = {}
        self._uploads_loaded = False
        self._fallback: Dataset | None = None
        self._last_scan: float = 0.0
        self._lock = threading.RLock()

    # ── bundled ──────────────────────────────────────────────────────────
    @property
    def registry_path(self) -> Path:
        return self.datasets_dir / "registry.json"

    def _bundled_signature(self) -> tuple[Any, ...]:
        try:
            st = self.registry_path.stat()
            return (st.st_mtime, st.st_size)
        except OSError:
            return (None, None)

    def _load_bundled(self) -> None:
        sig = self._bundled_signature()
        # re-scan when the registry changed, or every few seconds when entries are missing (files may appear later)
        if sig == self._bundled_sig and self._bundled and self._last_scan + 5 > time.monotonic():
            return
        found: dict[str, Dataset] = {}
        if self.registry_path.exists():
            try:
                entries = json.loads(self.registry_path.read_text(encoding="utf-8"))
                if isinstance(entries, dict):
                    entries = entries.get("datasets", [])
            except Exception as e:
                log.warning("unreadable datasets registry %s: %s", self.registry_path, e)
                entries = []
            for e in entries or []:
                if not isinstance(e, dict) or not e.get("id") or not e.get("file"):
                    continue
                path = (self.datasets_dir / str(e["file"])).resolve()
                if not path.exists() or path.stat().st_size == 0:
                    log.info("bundled dataset %s missing file %s (skipped for now)", e["id"], path)
                    continue
                prev = self._bundled.get(str(e["id"]))
                if prev is not None and prev.path == path:
                    prev.name = str(e.get("name") or prev.name)
                    prev.description = str(e.get("description") or prev.description)
                    prev.text_columns = [str(c) for c in e.get("text_columns") or []]
                    prev.suggested_questions = [str(q) for q in e.get("suggested_questions") or []]
                    found[prev.id] = prev
                    continue
                found[str(e["id"])] = Dataset(
                    id=str(e["id"]), name=str(e.get("name") or e["id"]), description=str(e.get("description") or ""),
                    source="bundled", text_columns=[str(c) for c in e.get("text_columns") or []],
                    suggested_questions=[str(q) for q in e.get("suggested_questions") or []], path=path,
                )
        self._bundled = found
        self._bundled_sig = sig
        self._last_scan = time.monotonic()

    # ── uploads ──────────────────────────────────────────────────────────
    @property
    def uploads_registry_path(self) -> Path:
        return self.uploads_dir / "registry.json"

    def _load_uploads(self) -> None:
        if self._uploads_loaded:
            return
        self._uploads_loaded = True
        if not self.uploads_registry_path.exists():
            return
        try:
            entries = json.loads(self.uploads_registry_path.read_text(encoding="utf-8"))
        except Exception as e:
            log.warning("unreadable uploads registry: %s", e)
            return
        for e in entries or []:
            if not isinstance(e, dict) or not e.get("id"):
                continue
            path = self.uploads_dir / str(e.get("file") or f"{e['id']}.csv")
            if not path.exists():
                continue
            self._uploads[str(e["id"])] = Dataset(
                id=str(e["id"]), name=str(e.get("name") or e["id"]), description=str(e.get("description") or ""),
                source="upload", text_columns=[str(c) for c in e.get("text_columns") or []],
                suggested_questions=[str(q) for q in e.get("suggested_questions") or list(DEFAULT_QUESTIONS)],
                path=path,
            )

    def _write_uploads_registry(self) -> None:
        entries = []
        for d in self._uploads.values():
            entries.append({
                "id": d.id, "name": d.name, "description": d.description, "file": d.path.name if d.path else None,
                "text_columns": d.text_columns, "suggested_questions": d.suggested_questions,
            })
        tmp = self.uploads_registry_path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(entries, indent=2), encoding="utf-8")
        tmp.replace(self.uploads_registry_path)

    def save_upload(self, filename: str, data: bytes) -> Dataset:
        if not data:
            raise DatasetError("empty_file", "the uploaded file is empty")
        if len(data) > MAX_UPLOAD_BYTES:
            raise DatasetError("file_too_large", f"CSV uploads are limited to {MAX_UPLOAD_BYTES // (1024 * 1024)} MB", 413)
        try:
            df = read_csv_bytes(data)
        except Exception as e:
            raise DatasetError("invalid_csv", f"could not parse CSV: {e}") from e
        if df.empty or len(df.columns) == 0:
            raise DatasetError("invalid_csv", "the CSV has no rows or no columns")
        # normalise column names: strip whitespace, de-duplicate, no empty names
        seen: dict[str, int] = {}
        names: list[str] = []
        for i, c in enumerate(df.columns):
            base = re.sub(r"\s+", " ", str(c)).strip() or f"column_{i + 1}"
            if base in seen:
                seen[base] += 1
                base = f"{base}_{seen[base]}"
            else:
                seen[base] = 0
            names.append(base)
        df.columns = names
        with self._lock:
            self._load_uploads()
            ds_id = f"up_{secrets.token_hex(4)}"
            while ds_id in self._uploads:
                ds_id = f"up_{secrets.token_hex(4)}"
            path = self.uploads_dir / f"{ds_id}.csv"
            df.to_csv(path, index=False)
            stem = Path(filename or "upload.csv").stem[:80] or "upload"
            ds = Dataset(
                id=ds_id, name=stem, source="upload",
                description=f"Uploaded CSV ({len(df):,} rows × {len(df.columns)} columns) — {now_iso()[:10]}",
                text_columns=infer_text_columns(df), suggested_questions=list(DEFAULT_QUESTIONS), path=path,
            )
            ds._frame = df
            ds._mtime = path.stat().st_mtime
            self._uploads[ds_id] = ds
            self._write_uploads_registry()
        return ds

    # ── public API ───────────────────────────────────────────────────────
    def list(self) -> list[Dataset]:
        with self._lock:
            self._load_bundled()
            self._load_uploads()
            items = list(self._bundled.values())
            if self.include_fallback and not items:
                items.append(self._get_fallback())
            items += list(self._uploads.values())
            return items

    def _get_fallback(self) -> Dataset:
        if self._fallback is None:
            self._fallback = fallback_dataset()
        return self._fallback

    def get(self, dataset_id: str) -> Dataset:
        with self._lock:
            self._load_bundled()
            self._load_uploads()
            ds = self._bundled.get(dataset_id) or self._uploads.get(dataset_id)
            if ds is None and self.include_fallback and dataset_id == FALLBACK_ID:
                ds = self._get_fallback()
            if ds is None:
                raise DatasetError("dataset_not_found", f"unknown dataset {dataset_id!r}", 404)
            return ds

    def preview(self, dataset_id: str, limit: int = 20) -> dict[str, Any]:
        return self.get(dataset_id).preview(limit)

    def csv_text(self, dataset_id: str) -> str:
        return self.get(dataset_id).csv_text()

    def delete_upload(self, dataset_id: str) -> bool:
        with self._lock:
            self._load_uploads()
            ds = self._uploads.pop(dataset_id, None)
            if ds is None:
                return False
            if ds.path and ds.path.exists():
                ds.path.unlink()
            self._write_uploads_registry()
            return True


_default_registry: DatasetRegistry | None = None


def get_registry() -> DatasetRegistry:
    global _default_registry
    if _default_registry is None:
        _default_registry = DatasetRegistry()
    return _default_registry


# module-level conveniences mirroring the registry API
def list_datasets() -> list[Dataset]:
    return get_registry().list()


def get(dataset_id: str) -> Dataset:
    return get_registry().get(dataset_id)


def preview(dataset_id: str, limit: int = 20) -> dict[str, Any]:
    return get_registry().preview(dataset_id, limit)


def csv_text(dataset_id: str) -> str:
    return get_registry().csv_text(dataset_id)
